/**
 * **版式基准** —— 全站通用的那一套排版规矩。
 *
 * 为什么单独一份:字号/图例/标题这些散在几十个渲染器里,各写各的 ⇒
 * 同一族里两个例子长得不一样、两个族的字号差一档,谁也说不清是设计还是手滑。
 * ⇒ 把「**所有家族都一样**」的那部分钉在这里,渲染器照着它;
 * 「**每个家族自己不一样**」的那部分留在各家族的 rules 里(那是性格,不是毛病)。
 *
 * 一条硬规矩:**读者是上了年纪的人** ⇒ 字号往大调,宁可图挤一点也要看得清。
 *
 * 固定不变的:
 *   - 字体:一律系统字体栈(不嵌 Inter 子集、不给文字描边)
 *   - 遮罩:用**垫色**(在字底下垫一块同色小矩形),不给字描边
 *   - 图例:坐**标题基线**那一行的左缘,不单独占一条带
 *   - 标题:左对齐,18px(editorial 家族的大标题另说,那是它的性格)
 *   - 空的东西不画:灰底纹轨道、没有数字的刻度线 ⇒ 想要标尺感走 `t=`
 *   - 宁可折行/缩放,不截断(截一半等于给错信息)
 *
 * 各家族自己定的(在 styles/*.ts 的 rules 里):
 *   - 标题的样式:plain(18px)/editorial(30px)/center(手绘风居中)
 *   - 圆角、图例符号(圆点/方块)、网格线型、扇区间隙…
 */

